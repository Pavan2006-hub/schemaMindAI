import re
import logging
from typing import Dict, Any, List
from core.schema_models import (
    DatabaseSchema,
    TableSchema,
    ColumnSchema,
    ForeignKeyConstraint,
    RelationshipSchema,
    RelationshipType
)
from core.gemma_client import GemmaClient

logger = logging.getLogger(__name__)

class SchemaAgent:
    """
    Schema Agent:
    Responsible for normalizing entities, resolving constraints, standardizing naming conventions,
    matching data types between foreign and primary keys, and ensuring 3NF relational standards.
    """

    TYPE_MAPPING = {
        "string": "VARCHAR(255)",
        "str": "VARCHAR(255)",
        "varchar": "VARCHAR(255)",
        "text": "TEXT",
        "longtext": "LONGTEXT",
        "int": "INT",
        "integer": "INT",
        "bigint": "BIGINT",
        "number": "INT",
        "float": "FLOAT",
        "double": "DOUBLE",
        "decimal": "DECIMAL(10,2)",
        "currency": "DECIMAL(10,2)",
        "money": "DECIMAL(10,2)",
        "price": "DECIMAL(10,2)",
        "bool": "BOOLEAN",
        "boolean": "BOOLEAN",
        "date": "DATE",
        "datetime": "DATETIME",
        "timestamp": "TIMESTAMP",
        "json": "JSON",
        "uuid": "VARCHAR(36)"
    }

    def __init__(self, gemma_client: GemmaClient):
        self.client = gemma_client

    def normalize_schema(self, raw_data: Dict[str, Any]) -> DatabaseSchema:
        """
        Transforms raw vision data into a validated, normalized DatabaseSchema.
        """
        db_name = self._to_snake_case(raw_data.get("database_name", "schemamind_db"))
        tables: List[TableSchema] = []
        relationships: List[RelationshipSchema] = []

        raw_tables = raw_data.get("tables", [])
        raw_relationships = raw_data.get("relationships", [])

        # Step 1: Normalize all tables and columns
        for t_data in raw_tables:
            table_name = self._to_snake_case(t_data.get("name", "unnamed_table"))
            columns: List[ColumnSchema] = []
            primary_keys: List[str] = []

            for col_data in t_data.get("columns", []):
                col_name = self._to_snake_case(col_data.get("name", "col"))
                raw_type = str(col_data.get("data_type", "VARCHAR(255)")).strip()
                norm_type = self._normalize_type(col_name, raw_type)

                is_pk = bool(col_data.get("is_primary_key", False) or col_name == "id")
                is_fk = bool(col_data.get("is_foreign_key", False) or (col_name.endswith("_id") and not is_pk))
                is_nullable = bool(col_data.get("is_nullable", not is_pk))
                is_unique = bool(col_data.get("is_unique", False))
                auto_inc = bool(col_data.get("auto_increment", is_pk and "INT" in norm_type))

                fk_target = col_data.get("foreign_key_target")

                column = ColumnSchema(
                    name=col_name,
                    data_type=norm_type,
                    is_primary_key=is_pk,
                    is_foreign_key=is_fk,
                    is_nullable=is_nullable,
                    is_unique=is_unique,
                    auto_increment=auto_inc,
                    default_value=col_data.get("default_value"),
                    comment=col_data.get("comment"),
                    foreign_key_target=fk_target
                )
                columns.append(column)

                if is_pk:
                    primary_keys.append(col_name)

            # Rule: Ensure at least one Primary Key exists
            if not primary_keys:
                id_col = ColumnSchema(
                    name="id",
                    data_type="BIGINT",
                    is_primary_key=True,
                    is_nullable=False,
                    auto_increment=True,
                    comment="Synthetic Primary Key auto-generated by SchemaAgent"
                )
                columns.insert(0, id_col)
                primary_keys.append("id")

            table = TableSchema(
                name=table_name,
                columns=columns,
                primary_keys=primary_keys,
                comment=t_data.get("comment")
            )
            tables.append(table)

        table_dict = {t.name: t for t in tables}

        # Step 2: Resolve Foreign Keys and Relationships
        # Check raw relationships
        for rel in raw_relationships:
            src = self._to_snake_case(rel.get("source_table", ""))
            tgt = self._to_snake_case(rel.get("target_table", ""))
            fk_col = rel.get("foreign_key")
            rel_type = rel.get("rel_type", "1:N")

            if src in table_dict and tgt in table_dict:
                relationships.append(
                    RelationshipSchema(
                        source_table=src,
                        target_table=tgt,
                        rel_type=RelationshipType(rel_type) if rel_type in ("1:1", "1:N", "N:1", "N:M") else RelationshipType.ONE_TO_MANY,
                        foreign_key=fk_col
                    )
                )

        # Step 3: Automatically link columns named `<parent>_id` as foreign keys
        for table in tables:
            for col in table.columns:
                if col.name.endswith("_id") and not col.is_primary_key:
                    parent_candidate = col.name[:-3]  # remove '_id'
                    # Check direct or plural match (e.g. user_id -> users, category_id -> categories)
                    target_table_name = None
                    if parent_candidate in table_dict:
                        target_table_name = parent_candidate
                    elif f"{parent_candidate}s" in table_dict:
                        target_table_name = f"{parent_candidate}s"
                    elif f"{parent_candidate}es" in table_dict:
                        target_table_name = f"{parent_candidate}es"
                    elif parent_candidate.endswith("y") and f"{parent_candidate[:-1]}ies" in table_dict:
                        target_table_name = f"{parent_candidate[:-1]}ies"

                    if target_table_name:
                        target_table = table_dict[target_table_name]
                        # Target primary key column
                        target_pk = target_table.primary_keys[0] if target_table.primary_keys else "id"
                        col.is_foreign_key = True
                        col.foreign_key_target = f"{target_table_name}.{target_pk}"

                        # Synchronize column data type to parent PK type!
                        target_pk_col = target_table.get_column(target_pk)
                        if target_pk_col:
                            col.data_type = target_pk_col.data_type

                        # Create explicit constraint
                        fk_constraint = ForeignKeyConstraint(
                            column_name=col.name,
                            target_table=target_table_name,
                            target_column=target_pk,
                            on_delete="CASCADE",
                            on_update="CASCADE"
                        )
                        # Check duplicate
                        if not any(f.column_name == col.name for f in table.foreign_keys):
                            table.foreign_keys.append(fk_constraint)

                        # Register relationship if not already tracked
                        if not any(r.source_table == target_table_name and r.target_table == table.name for r in relationships):
                            relationships.append(
                                RelationshipSchema(
                                    source_table=target_table_name,
                                    target_table=table.name,
                                    rel_type=RelationshipType.ONE_TO_MANY,
                                    foreign_key=col.name
                                )
                            )

        return DatabaseSchema(
            database_name=db_name,
            tables=tables,
            relationships=relationships
        )

    def _normalize_type(self, col_name: str, raw_type: str) -> str:
        """Heuristic and regex normalizer for SQL types."""
        clean = raw_type.lower().strip()
        # Direct lookup
        for key, val in self.TYPE_MAPPING.items():
            if key == clean:
                return val

        # Common name-based heuristics
        if col_name == "id" or col_name.endswith("_id"):
            return "BIGINT"
        if "price" in col_name or "amount" in col_name or "salary" in col_name or "total" in col_name:
            return "DECIMAL(10,2)"
        if "is_" in col_name or "has_" in col_name:
            return "BOOLEAN"
        if "created_at" in col_name or "updated_at" in col_name:
            return "TIMESTAMP"
        if "date" in col_name and "time" not in col_name:
            return "DATE"
        if "description" in col_name or "bio" in col_name or "content" in col_name:
            return "TEXT"

        # Check existing parentheses like VARCHAR(100)
        if "(" in raw_type and ")" in raw_type:
            return raw_type.upper()

        return "VARCHAR(255)"

    @staticmethod
    def _to_snake_case(name: str) -> str:
        """Converts PascalCase or camelCase to snake_case."""
        name = re.sub(r"[\s\-]+", "_", name.strip())
        s1 = re.sub("(.)([A-Z][a-z]+)", r"\1_\2", name)
        return re.sub("([a-z0-9])([A-Z])", r"\1_\2", s1).lower()
