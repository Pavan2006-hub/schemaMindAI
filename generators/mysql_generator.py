import datetime
from typing import List
from core.schema_models import DatabaseSchema, TableSchema, ColumnSchema

class MySQLGenerator:
    """
    MySQL Generator:
    Generates clean, battle-tested MySQL 8.0 DDL scripts with correct dependency ordering,
    strict foreign key constraints, indexes, and realistic seed data.
    """

    def generate_sql(self, schema: DatabaseSchema) -> str:
        """
        Generates full MySQL script.
        """
        now = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
        db_name = schema.database_name or "schemamind_db"

        lines: List[str] = [
            "-- ====================================================================",
            f"-- Database Schema: {db_name}",
            f"-- Generated by SchemaMindAI (Multi-Agent Gemma Engine)",
            f"-- Timestamp: {now}",
            "-- Compatible with MySQL 8.0+ / MariaDB 10.5+",
            "-- ====================================================================",
            "",
            "SET FOREIGN_KEY_CHECKS = 0;",
            "SET SQL_MODE = 'NO_AUTO_VALUE_ON_ZERO';",
            "",
            f"CREATE DATABASE IF NOT EXISTS `{db_name}`",
            "    CHARACTER SET utf8mb4",
            "    COLLATE utf8mb4_unicode_ci;",
            "",
            f"USE `{db_name}`;",
            ""
        ]

        # Topological sort for proper table creation order
        ordered_tables = schema.get_topological_order()

        # 1. DROP TABLE statements in reverse dependency order
        lines.append("-- --------------------------------------------------------------------")
        lines.append("-- Drop existing tables in reverse dependency order")
        lines.append("-- --------------------------------------------------------------------")
        for table in reversed(ordered_tables):
            lines.append(f"DROP TABLE IF EXISTS `{table.name}`;")
        lines.append("")

        # 2. CREATE TABLE statements in topological order
        lines.append("-- --------------------------------------------------------------------")
        lines.append("-- Table Definitions")
        lines.append("-- --------------------------------------------------------------------")
        for table in ordered_tables:
            lines.extend(self._generate_create_table(table))
            lines.append("")

        # 3. Seed sample data
        lines.append("-- --------------------------------------------------------------------")
        lines.append("-- Seed Sample Records for Testing")
        lines.append("-- --------------------------------------------------------------------")
        for table in ordered_tables:
            seed_sql = self._generate_sample_inserts(table)
            if seed_sql:
                lines.append(seed_sql)

        lines.extend([
            "",
            "SET FOREIGN_KEY_CHECKS = 1;",
            "-- ====================================================================",
            "-- End of SchemaMindAI MySQL Script",
            "-- ===================================================================="
        ])

        return "\n".join(lines)

    def _generate_create_table(self, table: TableSchema) -> List[str]:
        lines: List[str] = [f"CREATE TABLE `{table.name}` ("]
        col_defs: List[str] = []

        # Columns
        for col in table.columns:
            parts = [f"    `{col.name}` {col.data_type}"]

            if not col.is_nullable:
                parts.append("NOT NULL")

            if col.auto_increment:
                parts.append("AUTO_INCREMENT")

            if col.default_value is not None:
                parts.append(f"DEFAULT {col.default_value}")

            if col.is_unique and not col.is_primary_key:
                parts.append("UNIQUE")

            if col.comment:
                comment_clean = col.comment.replace("'", "''")
                parts.append(f"COMMENT '{comment_clean}'")

            col_defs.append(" ".join(parts))

        # Primary Key constraint
        if table.primary_keys:
            pk_cols = ", ".join(f"`{k}`" for k in table.primary_keys)
            col_defs.append(f"    PRIMARY KEY ({pk_cols})")

        # Foreign Key constraints
        for fk in table.foreign_keys:
            fk_name = f"fk_{table.name}_{fk.column_name}"
            fk_sql = (
                f"    CONSTRAINT `{fk_name}` FOREIGN KEY (`{fk.column_name}`) "
                f"REFERENCES `{fk.target_table}` (`{fk.target_column}`) "
                f"ON DELETE {fk.on_delete} ON UPDATE {fk.on_update}"
            )
            col_defs.append(fk_sql)

        # Indexes for foreign key columns for fast JOIN queries
        for fk in table.foreign_keys:
            idx_name = f"idx_{table.name}_{fk.column_name}"
            col_defs.append(f"    INDEX `{idx_name}` (`{fk.column_name}`)")

        lines.append(",\n".join(col_defs))
        tbl_comment = f" COMMENT='{table.comment}'" if table.comment else ""
        lines.append(f") ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci{tbl_comment};")
        return lines

    def _generate_sample_inserts(self, table: TableSchema) -> str:
        """Generates realistic sample rows for testing."""
        cols_to_insert = [c for c in table.columns if not c.auto_increment]
        if not cols_to_insert:
            return ""

        col_names = ", ".join(f"`{c.name}`" for c in cols_to_insert)

        sample_vals_1 = []
        sample_vals_2 = []

        for c in cols_to_insert:
            val1, val2 = self._get_sample_value(c)
            sample_vals_1.append(val1)
            sample_vals_2.append(val2)

        row1 = ", ".join(sample_vals_1)
        row2 = ", ".join(sample_vals_2)

        return (
            f"INSERT INTO `{table.name}` ({col_names}) VALUES\n"
            f"    ({row1}),\n"
            f"    ({row2});"
        )

    def _get_sample_value(self, col: ColumnSchema) -> tuple:
        """Returns dummy literal values based on column type and name."""
        t = col.data_type.upper()
        name = col.name.lower()

        if col.is_foreign_key or name.endswith("_id"):
            return ("1", "2")
        if "INT" in t:
            return ("100", "200")
        if "DECIMAL" in t or "FLOAT" in t or "DOUBLE" in t:
            return ("49.99", "129.50")
        if "BOOLEAN" in t:
            return ("TRUE", "FALSE")
        if "TIMESTAMP" in t or "DATETIME" in t:
            return ("NOW()", "NOW()")
        if "DATE" in t:
            return ("'2026-01-15'", "'2026-02-20'")

        # Strings
        if "email" in name:
            return ("'alice@example.com'", "'bob@example.com'")
        if "username" in name or "user" in name:
            return ("'alice_dev'", "'bob_builder'")
        if "name" in name:
            return ("'Standard Item Alpha'", "'Premium Item Beta'")
        if "phone" in name:
            return ("'+1-555-0199'", "'+1-555-0144'")
        if "status" in name:
            return ("'ACTIVE'", "'COMPLETED'")
        if "password" in name or "hash" in name:
            return ("'$2y$12$e8YkZ8h7...hashed'", "'$2y$12$q7WpZ9m2...hashed'")

        return (f"'{col.name}_val_1'", f"'{col.name}_val_2'")
